-- ================================================================
-- V2 — Create Account Tables
-- ================================================================
--
-- The account module OWNS these tables.
--
-- Notice: accounts reference customers by customer_id (a UUID).
-- The account module does NOT join to the customers table at query time.
-- It stores the customer_id as a reference and calls CustomerService
-- when it needs customer details.
--
-- This is how we maintain module data independence while still using
-- a single shared database. The foreign key is intentionally NOT
-- declared as a database-level FK constraint between modules, because:
-- 1. It would create a hard schema dependency between modules
-- 2. If we ever extract Account into a microservice, we'd need to
--    remove that FK anyway
-- 3. Referential integrity is maintained at the application layer
--    via the CustomerService.exists() check during account creation
--
-- This is a deliberate design decision, not an oversight.
-- ================================================================

CREATE TABLE accounts
(
    id              UUID                     NOT NULL DEFAULT gen_random_uuid(),

    -- Reference to the owning customer.
    -- Stored as UUID — no foreign key constraint to customers table.
    -- The Account module treats this as an opaque reference ID.
    customer_id     UUID                     NOT NULL,

    -- Human-readable account number (e.g., "ACC-00000001")
    -- Generated by the application, not the database.
    account_number  VARCHAR(20)              NOT NULL,

    -- Account type determines interest rates, limits, and rules.
    account_type    VARCHAR(50)              NOT NULL,

    -- Account lifecycle status
    -- PENDING   → Created but not yet activated
    -- ACTIVE    → Fully operational
    -- FROZEN    → Temporarily blocked (fraud, legal hold)
    -- CLOSED    → Permanently closed
    status          VARCHAR(50)              NOT NULL DEFAULT 'PENDING',

    -- Balance stored as NUMERIC with precision 19, scale 4.
    --
    -- WHY NOT DOUBLE/FLOAT?
    -- IEEE 754 floating point cannot represent many decimal fractions
    -- exactly. For example: 0.1 + 0.2 = 0.30000000000000004 in float.
    -- In banking, ₹0.0000000000001 discrepancy compounds across millions
    -- of transactions and creates reconciliation nightmares.
    --
    -- NUMERIC(19, 4) means:
    -- - Up to 19 total significant digits
    -- - Always exactly 4 decimal places
    -- - Stored and computed in exact decimal arithmetic by PostgreSQL
    --
    -- Java side: always use BigDecimal, never double or float.
    balance         NUMERIC(19, 4)           NOT NULL DEFAULT 0.0000,

    -- The currency code (ISO 4217): INR, USD, EUR, etc.
    currency        VARCHAR(3)               NOT NULL DEFAULT 'INR',

    -- Minimum balance requirement (for savings accounts)
    minimum_balance NUMERIC(19, 4)           NOT NULL DEFAULT 0.0000,

    -- Audit columns
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    created_by      VARCHAR(255)             NOT NULL DEFAULT 'SYSTEM',

    -- Optimistic locking — CRITICAL for account balance updates.
    -- Without this, two concurrent withdrawals can both read the same
    -- balance, both see "sufficient funds", and both deduct —
    -- resulting in a negative balance. Version prevents this.
    version         BIGINT                   NOT NULL DEFAULT 0,

    CONSTRAINT pk_accounts PRIMARY KEY (id),
    CONSTRAINT uq_accounts_number UNIQUE (account_number)
);

-- Index for looking up all accounts belonging to a customer
CREATE INDEX idx_accounts_customer_id ON accounts (customer_id);

-- Index for account number lookup (used in transfers)
CREATE INDEX idx_accounts_number ON accounts (account_number);

-- Index for status filtering (find all ACTIVE accounts, etc.)
CREATE INDEX idx_accounts_status ON accounts (status);
